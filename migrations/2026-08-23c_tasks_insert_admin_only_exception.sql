-- BSD-CRM — tasks_insert: restrict the "assign to another user" exception
-- to admin only (was admin OR manager)
-- תאריך: 23/08/2026
-- ============================================================================
-- הבהרה שקיבל: manager אינו אדמין ואסור לו לקבל עקיפה אוטומטית של הכלל
-- "כל משתמש יוצר משימה רק לעצמו". בדקתי אם קיימת תלות קיימת ומאושרת -
-- ה-manager הוכנס למדיניות tasks (select/update/delete וגם ה-insert
-- שנוצר הרגע) לפי הערה מפורשת ב-2026-08-15d: "מוסיף גם manager לצד admin,
-- ליישור עם אותה קונבנציה שקיימת בכל שאר המערכת (...) אם תרצה שמנהל לא
-- יראה הכל, תגיד ואני אצמצם" - כלומר זו הייתה הנחת ברירת מחדל, מעולם לא
-- אישור מפורש שלו במיוחד לגבי משימות. אין תלות מאושרת שמחייבת אחרת.
--
-- תיקון זה: manager עדיין יכול ליצור משימה לעצמו (assigned_to = עצמו,
-- מותר לכולם), אבל כבר לא יכול להקצות משימה למשתמש אחר - זה שמור ל-admin
-- בלבד מעכשיו.
--
-- הערה: tasks_select / tasks_update / tasks_delete עדיין כוללים manager
-- לצד admin (רואה הכל, עורך הכל) - זה נשאר כפי שהיה, לא נגעתי בזה כאן.
-- אם רוצים גם שם manager לא יראה משימות של אחרים, זה שינוי נפרד שדורש
-- אישור מפורש בפני עצמו.
-- ============================================================================

drop policy if exists "tasks_insert" on tasks;
create policy "tasks_insert" on tasks for insert with check (
  assigned_to = auth.uid()
  or exists (select 1 from profiles p where p.id = auth.uid() and p.role = 'admin')
);
